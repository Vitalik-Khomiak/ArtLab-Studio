function detailValue(value) {
    if (Array.isArray(value)) return value.filter(Boolean);
    const translated = localized(value);
    return translated ? [translated] : [];
}

function detailSection(title, values) {
    if (!values.length) return "";
    const body = values.length > 1
        ? `<ul>${values.map((value) => `<li>${escapeHtml(value)}</li>`).join("")}</ul>`
        : `<p>${escapeHtml(values[0])}</p>`;

    return `
        <section class="modal-detail-block">
            <h3>${escapeHtml(title)}</h3>
            ${body}
        </section>
    `;
}

function renderModal() {
    const project = findProject(state.modalId);
    if (!project) return;

    const mediaItems = modalMediaItems(project);
    const currentMedia = mediaItems[state.modalImageIndex] || mediaItems[0];

    els.modalMedia.innerHTML = modalMediaMarkup(currentMedia, project);
    els.modalMeta.textContent = projectMeta(project);
    els.modalTitle.textContent = project.title;
    els.modalDescription.textContent = localized(project.description);
    els.modalTags.innerHTML = tagMarkup(project.tags);
    els.modalFacts.innerHTML = `
        <div>
            <dt>${escapeHtml(text("fact.role"))}</dt>
            <dd>${escapeHtml(localized(project.role))}</dd>
        </div>
        <div>
            <dt>${escapeHtml(text("fact.focus"))}</dt>
            <dd>${escapeHtml(localized(project.focus))}</dd>
        </div>
    `;

    const detailHtml = [
        detailSection(text("modal.brief"), detailValue(project.brief)),
        detailSection(text("modal.process"), detailValue(project.process)),
        detailSection(text("modal.result"), detailValue(project.result)),
        detailSection(text("modal.deliverables"), detailValue(project.deliverables)),
        detailSection(text("modal.tools"), detailValue(project.tools))
    ].filter(Boolean).join("");

    els.modalDetails.innerHTML = detailHtml;
    els.modalDetails.hidden = detailHtml.length === 0;

    els.modalThumbs.innerHTML = mediaItems.length > 1
        ? mediaItems.map((item, index) => `
            <button class="thumb-btn${index === state.modalImageIndex ? " is-active" : ""}" type="button"
                data-thumb-index="${index}" aria-label="${escapeHtml(project.title)} media ${index + 1}">
                ${item.type === "video"
                    ? `<img src="${escapeHtml(project.cover)}" alt="" loading="lazy">`
                    : `<img src="${escapeHtml(item.src)}" alt="" loading="lazy">`}
            </button>
        `).join("")
        : "";

    els.modalThumbs.querySelectorAll("[data-thumb-index]").forEach((button) => {
        button.addEventListener("click", () => {
            state.modalImageIndex = Number(button.dataset.thumbIndex);
            renderModal();
        });
    });
}

function openModal(id) {
    if (!findProject(id)) return;

    state.modalId = id;
    state.modalImageIndex = 0;
    renderModal();
    els.modal.classList.add("is-open");
    els.modal.setAttribute("aria-hidden", "false");
    document.body.classList.add("modal-open");
    els.modalClose.focus();
}

function closeModal() {
    els.modal.classList.remove("is-open");
    els.modal.setAttribute("aria-hidden", "true");
    document.body.classList.remove("modal-open");
    els.modalMedia.innerHTML = "";
    state.modalId = null;
}

function stepModal(direction) {
    if (!state.modalId) return;

    const list = sortedProjects();
    const position = list.findIndex((project) => project.id === state.modalId);
    const nextPosition = position === -1
        ? 0
        : (position + direction + list.length) % list.length;

    state.modalId = list[nextPosition].id;
    state.modalImageIndex = 0;
    renderModal();
}

function renderAll() {
    updateStaticCopy();
    renderCases();
    renderArchive();
    setFeatured(state.featuredId);

    if (state.modalId) {
        renderModal();
    }
}

els.langBtn.addEventListener("click", () => {
    state.lang = state.lang === "en" ? "uk" : "en";
    renderAll();
});

els.modalClose.addEventListener("click", closeModal);
els.modalPrev.addEventListener("click", () => stepModal(-1));
els.modalNext.addEventListener("click", () => stepModal(1));

els.modal.addEventListener("click", (event) => {
    if (event.target === els.modal) {
        closeModal();
    }
});

document.addEventListener("keydown", (event) => {
    if (!state.modalId) return;

    if (event.key === "Escape") closeModal();
    if (event.key === "ArrowRight") stepModal(1);
    if (event.key === "ArrowLeft") stepModal(-1);
});

renderAll();
